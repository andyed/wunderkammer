#!/usr/bin/env node
import { chromium } from 'playwright';
import { mkdir,writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const target=process.env.COMPARISON_URL;
if(!target)throw new Error('Set COMPARISON_URL to the verified comparison instance.');
const out=path.resolve(process.env.COMPARISON_PROOF_DIR||'.local/comparison-spike/walls-proof');
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[],report={url:target};
const ready=async p=>{await p.waitForSelector('body[data-scene-ready=true]');await p.waitForFunction(()=>window.comparisonDebug().scene.rendered);};
const loaded=async p=>{await p.waitForFunction(()=>{const s=window.comparisonDebug().scene;return s.totalTiles>0&&s.loadedArtwork+s.failedArtwork===new Set(window.comparisonDebug().cohorts.flatMap(c=>c.keys)).size;},{},{timeout:60000});};
function listen(p){p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error'&&/THREE|WebGL|shader/i.test(m.text()))errors.push(m.text());});}
try{
  const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce'});listen(page);
  await page.goto(target);await ready(page);
  if((await page.evaluate(()=>window.comparisonDebug())).presentation.view!=='walls')await page.locator('[data-view=walls]').click();
  await loaded(page);
  const initial=await page.evaluate(()=>window.comparisonDebug());
  assert.equal(initial.scene.totalTiles,initial.cohorts.reduce((n,c)=>n+c.count,0));
  assert(initial.scene.loadedArtwork>100);assert.equal(initial.scene.failedArtwork,0);
  assert(initial.scene.atlasPages<=Math.ceil(initial.evidenceKeys.length/256));
  assert(initial.scene.pickTargets.length>0);
  report.initial=initial.scene;
  await page.locator('#scope-panel summary').click();
  await page.selectOption('#metric','count');
  const counted=await page.evaluate(()=>window.comparisonDebug());
  assert.equal(counted.scene.loadedArtwork,initial.scene.loadedArtwork,'metric changes reuse decoded artwork');
  assert.deepEqual(counted.scene.pickTargets,initial.scene.pickTargets,'metric changes preserve cover geometry');
  assert.deepEqual(counted.evidenceKeys,initial.evidenceKeys);
  await page.selectOption('#metric','share');
  await page.locator('#scope-panel summary').click();
  report.metricPreservesArtworks=true;
  await page.locator('#comparison-stage').screenshot({path:path.join(out,'album-walls.png')});
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
  const box=await page.locator('#comparison-stage canvas').boundingBox(),pick=initial.scene.pickTargets[0];
  await page.mouse.click(box.x+(pick.x*.5+.5)*box.width,box.y+(-pick.y*.5+.5)*box.height);
  await page.waitForSelector('#item-dialog[open]');
  assert.equal((await page.evaluate(()=>window.comparisonDebug())).focus,pick.key);
  report.exactCoverPick={key:pick.key,cohort:pick.cohort,title:await page.locator('#item-title').textContent()};
  await page.keyboard.press('Escape');await page.mouse.move(0,0);
  await page.locator('.category-button').first().click();
  await page.mouse.move(0,0);
  const selected=await page.evaluate(()=>window.comparisonDebug());
  const row=selected.rows.find(r=>r.value===selected.selection.value);
  assert.equal(selected.scene.highlightedTiles,row.cells.reduce((n,c)=>n+c.count,0));
  assert.equal(selected.scene.totalTiles,initial.scene.totalTiles);
  await page.locator('#aisle-travel').fill('65');await page.locator('#aisle-travel').dispatchEvent('input');
  await page.locator('#comparison-stage canvas').focus();await page.keyboard.press('ArrowLeft');
  const walked=await page.evaluate(()=>window.comparisonDebug());
  assert.deepEqual(walked.evidenceKeys,selected.evidenceKeys);
  assert.notDeepEqual(walked.scene.camera,initial.scene.camera);
  assert.equal(new URL(page.url()).searchParams.get('travel'),'0.65');
  await page.locator('#comparison-stage').screenshot({path:path.join(out,'walked-selection.png')});
  const savedURL=page.url(),fresh=await browser.newPage({viewport:{width:1440,height:1050}});listen(fresh);
  await fresh.goto(savedURL);await ready(fresh);
  const restored=await fresh.evaluate(()=>window.comparisonDebug());
  assert.deepEqual(restored.presentation,walked.presentation);assert.deepEqual(restored.evidenceKeys,walked.evidenceKeys);
  for(const axis of ['position','target'])walked.scene.camera[axis].forEach((n,i)=>assert(Math.abs(n-restored.scene.camera[axis][i])<.0001));
  await fresh.close();report.freshViewRestored=true;report.walkPreservesEvidence=true;
  await page.selectOption('#depth-slice',initial.cohorts[0].key);
  assert.equal((await page.evaluate(()=>window.comparisonDebug())).scene.visibleCohorts,1);
  assert.deepEqual((await page.evaluate(()=>window.comparisonDebug())).evidenceKeys,selected.evidenceKeys);
  await page.selectOption('#depth-slice','');await page.locator('[data-view=depth]').click();
  assert((await page.evaluate(()=>window.comparisonDebug())).scene.bars>0);
  await page.locator('[data-view=walls]').click();
  assert.equal((await page.evaluate(()=>window.comparisonDebug())).scene.totalTiles,initial.scene.totalTiles);
  report.chartRoundTrip=true;
  const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});listen(phone);
  const phoneURL=new URL(target);phoneURL.searchParams.set('view','walls');phoneURL.searchParams.delete('camera');
  await phone.goto(phoneURL.href);await ready(phone);await loaded(phone);
  const phoneData=await phone.evaluate(()=>window.comparisonDebug());
  assert(phoneData.scene.pickTargets.length>0);
  await phone.locator('#comparison-stage').scrollIntoViewIfNeeded();
  await phone.screenshot({path:path.join(out,'phone.png')});
  const rect=await phone.locator('#comparison-stage canvas').boundingBox(),tap=phoneData.scene.pickTargets[0];
  await phone.touchscreen.tap(rect.x+(tap.x*.5+.5)*rect.width,rect.y+(-tap.y*.5+.5)*rect.height);
  await phone.waitForSelector('#item-dialog[open]');assert.equal((await phone.evaluate(()=>window.comparisonDebug())).focus,tap.key);
  await phone.getByRole('button',{name:'Close item',exact:true}).tap();
  report.phone=await phone.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.equal(report.phone.width,report.phone.scroll);report.touchCoverPick=true;
  assert.deepEqual(errors,[]);report.errors=errors;
  await writeFile(path.join(out,'verification.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify({passed:true,proof:out,tiles:initial.scene.totalTiles,loaded:initial.scene.loadedArtwork,pages:initial.scene.atlasPages,draws:initial.scene.renderCalls,exactPick:report.exactCoverPick,phone:report.phone}));
}finally{await browser.close();}
