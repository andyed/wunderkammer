#!/usr/bin/env node
/** Read-only live proof against a running Music Atlas. Writes local screenshots. */
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
const origin = process.env.MUSIC_ATLAS_URL || 'http://127.0.0.1:4175';
const output = path.resolve('.local/music-atlas');
await mkdir(output, { recursive: true });
const data = await (await fetch(origin + '/api/clips')).json();
assert(data.clips.length > 0, 'music index is empty');
const browser = await chromium.launch();
const errors = [];
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(origin, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('body[data-view-ready="true"]');
  await page.waitForFunction(() => [...document.querySelectorAll('.tile img')].every(i => i.src && !i.dataset.src && i.complete && i.naturalWidth > 0), null, { timeout: 90000 });
  await page.evaluate(async () => { await Promise.all([...document.querySelectorAll('.tile img')].map(i => i.decode())); await new Promise(requestAnimationFrame); await new Promise(requestAnimationFrame); });
  await page.screenshot({ path: path.join(output, 'music-overview.png') });
  assert.equal(await page.title(), 'Music Atlas');
  const artist = data.clips.some(c => c.props.artist === 'Talking Heads') ? 'Talking Heads' : data.clips[0].props.artist;
  await page.locator('#search').fill(artist);
  await page.waitForTimeout(1000);
  const visible = await page.locator('#count').innerText();
  assert(!visible.startsWith('0 '), 'artist search has results');
  await page.locator('.tile').first().click();
  await page.waitForSelector('#detail.open');
  await page.waitForTimeout(800);
  const heading = await page.locator('#detail h2').innerText();
  assert(heading.length > 0);
  await page.getByRole('button', { name: 'Copy link', exact: true }).click();
  const link = await page.evaluate(() => navigator.clipboard.readText());
  assert(new URL(link).hash.includes('v=1'));
  const fresh = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
  const restored = await fresh.newPage();
  restored.on('pageerror', error => errors.push(error.message));
  await restored.goto(link, { waitUntil: 'domcontentloaded' });
  await restored.waitForSelector('body[data-view-ready="true"]');
  assert.equal(await restored.locator('#search').inputValue(), artist);
  assert.equal(await restored.locator('#count').innerText(), visible);
  assert.equal(await restored.locator('#detail h2').innerText(), heading);
  await restored.waitForFunction(() => [...document.querySelectorAll('#detail img')].every(i => i.complete && i.naturalWidth > 0));
  await restored.screenshot({ path: path.join(output, 'music-detail.png') });
  await restored.setViewportSize({ width: 700, height: 900 });
  await restored.waitForTimeout(400);
  const detail = await restored.locator('#detail').boundingBox();
  assert(detail.width >= 690 && detail.x >= -1, 'narrow inspector fits the screen');
  await restored.getByRole('button', { name: 'Close', exact: true }).click();
  await restored.locator('#search').fill('');
  await restored.waitForTimeout(800);
  await restored.locator('.tile').first().focus();
  await restored.keyboard.press('Enter');
  await restored.waitForSelector('#detail.open');
  assert.deepEqual(errors, []);
  const result = { albums: data.clips.length, artist, visible, heading, link, errors };
  await writeFile(path.join(output, 'music-proof.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
